import type { HLJSApi, Language } from "highlight.js";

/** SPARQL 1.1 query and update language for highlight.js, which has no built-in definition */
export default function sparql(hljs: HLJSApi): Language {
  return {
    name: "SPARQL",
    aliases: ["rq"],
    case_insensitive: true,
    keywords: {
      keyword: [
        "select",
        "construct",
        "describe",
        "ask",
        "where",
        "from",
        "named",
        "prefix",
        "base",
        "optional",
        "filter",
        "union",
        "minus",
        "graph",
        "service",
        "silent",
        "bind",
        "as",
        "values",
        "order",
        "by",
        "asc",
        "desc",
        "group",
        "having",
        "limit",
        "offset",
        "distinct",
        "reduced",
        "not",
        "exists",
        "in",
        "insert",
        "delete",
        "data",
        "with",
        "using",
        "default",
        "all",
        "load",
        "clear",
        "drop",
        "create",
        "add",
        "move",
        "copy",
        "to",
        "into",
        "undef",
        "separator",
        // Shortcut for rdf:type
        "a",
      ],
      literal: ["true", "false"],
      built_in: [
        "str",
        "lang",
        "langmatches",
        "datatype",
        "bound",
        "iri",
        "uri",
        "bnode",
        "rand",
        "abs",
        "ceil",
        "floor",
        "round",
        "concat",
        "strlen",
        "ucase",
        "lcase",
        "encode_for_uri",
        "contains",
        "strstarts",
        "strends",
        "strbefore",
        "strafter",
        "year",
        "month",
        "day",
        "hours",
        "minutes",
        "seconds",
        "timezone",
        "tz",
        "now",
        "uuid",
        "struuid",
        "md5",
        "sha1",
        "sha256",
        "sha384",
        "sha512",
        "coalesce",
        "if",
        "strlang",
        "strdt",
        "sameterm",
        "isiri",
        "isuri",
        "isblank",
        "isliteral",
        "isnumeric",
        "regex",
        "substr",
        "replace",
        "count",
        "sum",
        "min",
        "max",
        "avg",
        "sample",
        "group_concat",
      ],
    },
    contains: [
      hljs.HASH_COMMENT_MODE,
      // Full IRIs, without spaces so comparisons like `?a < 5 && ?b > 2` are not taken for one
      { scope: "title", match: /<[^<>"{}|^`\\\s]*>/ },
      { scope: "variable", match: /[?$][\w]+/ },
      // Triple quoted strings first, they can hold quotes and line breaks
      { scope: "string", begin: '"""', end: '"""', contains: [hljs.BACKSLASH_ESCAPE] },
      { scope: "string", begin: "'''", end: "'''", contains: [hljs.BACKSLASH_ESCAPE] },
      hljs.QUOTE_STRING_MODE,
      hljs.APOS_STRING_MODE,
      // Language tag of a literal, e.g. "chat"@fr
      { scope: "meta", match: /@[a-zA-Z]+(?:-[a-zA-Z0-9]+)*/ },
      // Prefixed names (up:Protein, rdfs:, :local) and blank nodes (_:b0), a trailing dot ends the triple
      { scope: "attr", match: /(?:[A-Za-z_][\w-]*)?:[\w-]*(?:\.[\w-]+)*/ },
      hljs.C_NUMBER_MODE,
    ],
  };
}
